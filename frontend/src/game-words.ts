type Core = { question: string; correct: string; options: string[]; explanation: string; intro?: string; stimulus?: GameTask['stimulus']; chip?: string }

const TIME: Record<Level, number> = { 1: 18, 2: 16, 3: 14 }

function genAnagram(level: Level): Core {
  const word = pickFresh(ANAGRAM_WORDS[level], (w) => w, 'an')
  const shown = scramble(word)
  let decoys = decoysFor(word, shown)
  let guard = 0
  while (decoys.length < 3 && guard++ < 50) {
    const d = scramble(word)
    if (d !== shown && d !== word && !ALL_KNOWN.has(d) && !decoys.includes(d)) decoys.push(d)
  }
  decoys = decoys.slice(0, 3)
  return {
    intro: level === 1 ? `Подсказка: начинается на «${word[0].toUpperCase()}»` : undefined,
    stimulus: { type: 'text', text: shown.toUpperCase(), size: 'xl' },
    question: 'Какое слово спрятано?',
    correct: word,
    options: shuffle([word, ...decoys]),
    explanation: `Из букв «${shown.toUpperCase()}» получается слово «${word}».`,
  }
}

const VOWELS = 'аеиоуыэюя'

function genMissing(level: Level): Core {
  const pool = MISSING_WORDS[level]
  const [word, idx, wrongs] = pickFresh(pool, (m) => m[0] + m[1], 'ms')
  const letter = word[idx].toUpperCase()
  const wrongLetters = shuffle(wrongs.toUpperCase().split('').filter((c) => c !== letter)).slice(0, 3)
  const stem = (word.slice(0, idx) + '_' + word.slice(idx + 1)).toUpperCase()
  const kind = VOWELS.includes(word[idx]) ? 'гласная' : 'согласная'
  return {
    stimulus: { type: 'text', text: stem, size: 'xl' },
    question: 'Какой буквы не хватает?',
    correct: letter,
    options: shuffle([letter, ...wrongLetters]),
    explanation: `Слово «${word}»: пропущена ${kind} «${letter}».`,
  }
}

function synonymPool(level: Level): SynGroup[] {
  const levels: Level[] = level === 1 ? [1] : level === 2 ? [1, 2] : [2, 3]
  return levels.flatMap((l) => SYN_GROUPS[l])
}

function distinctTagWords(cands: SynGroup[], n: number): string[] {
  const seen = new Set<string>()
  const out: string[] = []
  for (const g of shuffle(cands)) {
    if (seen.has(g.tag)) continue
    seen.add(g.tag)
    out.push(pickOne(g.w))
    if (out.length >= n) break
  }
  return out
}

function genSynonym(level: Level): Core {
  const groups = SYN_GROUPS[level]
  const g = pickFresh(groups, (x) => x.w[0], 'sy', 40)
  const [key, answer] = shuffle(g.w).slice(0, 2)
  let decoys = distinctTagWords(synonymPool(level).filter((x) => x.pos === g.pos && x.tag !== g.tag), 3)
  if (decoys.length < 3) {
    const all = [...SYN_GROUPS[1], ...SYN_GROUPS[2], ...SYN_GROUPS[3]]
    decoys = distinctTagWords(all.filter((x) => x.pos === g.pos && x.tag !== g.tag), 3)
  }
  return {
    question: `Найди синоним к слову «${key}»`,
    correct: answer,
    options: shuffle([answer, ...decoys]),
    explanation: `Слова «${key}» и «${answer}» близки по смыслу — это синонимы.`,
  }
}

const SYN_OF = new Map<string, Set<string>>()
for (const l of [1, 2, 3] as Level[]) {
  for (const g of SYN_GROUPS[l]) {
    for (const w of g.w) {
      const set = SYN_OF.get(w) || new Set<string>()
      for (const o of g.w) if (o !== w) set.add(o)
      SYN_OF.set(w, set)
    }
  }
}

function genAntonym(level: Level): Core {
  const pair = pickFresh(ANT_PAIRS[level], (p) => p[0], 'an2', 40)
  const flip = Math.random() < 0.5
  const key = flip ? pair[1] : pair[0]
  const answer = flip ? pair[0] : pair[1]
  const levels: Level[] = level === 1 ? [1] : level === 2 ? [1, 2] : [2, 3]
  const pool = (ls: Level[]) => ls.flatMap((l) => ANT_PAIRS[l]).filter((p) => p[3] === pair[3] && p[2] !== pair[2])
  const pick = (cands: AntPair[]): string[] => {
    const seen = new Set<string>()
    const out: string[] = []
    for (const p of shuffle(cands)) {
      if (seen.has(p[2])) continue
      const w = Math.random() < 0.5 ? p[0] : p[1]
      if (SYN_OF.get(key)?.has(w) || SYN_OF.get(answer)?.has(w)) continue
      seen.add(p[2])
      out.push(w)
      if (out.length >= 3) break
    }
    return out
  }
  let decoys = pick(pool(levels))
  if (decoys.length < 3) decoys = pick(pool([1, 2, 3]))
  return {
    question: `Найди антоним к слову «${key}»`,
    correct: answer,
    options: shuffle([answer, ...decoys]),
    explanation: `Слова «${key}» и «${answer}» противоположны по смыслу — это антонимы.`,
  }
}

