// Замены в «почти анаграммах»: одна буква меняется на похожую
const SWAP_LETTER: Record<string, string> = {
  а: 'о', о: 'а', е: 'и', и: 'е', у: 'о', б: 'п', п: 'б', д: 'т', т: 'д', з: 'с', с: 'з', в: 'ф', г: 'к', к: 'г', ж: 'ш', ш: 'ж', л: 'р', р: 'л', м: 'н', н: 'м',
}

function samePositions(a: string, b: string): number {
  let n = 0
  for (let i = 0; i < a.length; i++) if (a[i] === b[i]) n++
  return n
}

// Перемешивание букв так, чтобы слово не читалось (совпадений на своих местах немного)
function scramble(word: string): string {
  const letters = word.split('')
  for (let i = 0; i < 60; i++) {
    const s = shuffle(letters).join('')
    if (s !== word && samePositions(s, word) <= Math.floor(word.length / 4)) return s
  }
  return shuffle(letters).reverse().join('')
}

// Лжеслова: перестановки двух букв или замена буквы на похожую — «слова» получаются непроизносимыми
function decoysFor(word: string, shown: string): string[] {
  const out = new Set<string>()
  const n = word.length
  let guard = 0
  while (out.size < 3 && guard++ < 200) {
    const a = word.split('')
    if (Math.random() < 0.7) {
      const i = rand(1, n - 2)
      const j = Math.min(n - 1, i + rand(1, 3))
      ;[a[i], a[j]] = [a[j], a[i]]
    } else {
      const i = rand(1, n - 1)
      const r = SWAP_LETTER[a[i]]
      if (!r) continue
      a[i] = r
      if (Math.random() < 0.5 && n > 5) { const k = rand(1, n - 2); if (k !== i) [a[k], a[k + 1]] = [a[k + 1], a[k]] }
    }
    const d = a.join('')
    if (d !== word && d !== shown && !ALL_KNOWN.has(d)) out.add(d)
  }
  return [...out]
}

