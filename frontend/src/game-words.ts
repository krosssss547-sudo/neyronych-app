const round1 = (x: number) => Math.round(x * 10) / 10

function plural(n: number, one: string, few: string, many: string): string {
  const m10 = n % 10
  const m100 = n % 100
  if (m10 === 1 && m100 !== 11) return one
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return few
  return many
}

// Недавние элементы банков (общий счётчик, ключи с префиксом вида)
const recent = makeRecent(40)
function pickFresh<T>(bank: T[], key: (x: T) => string, prefix: string, tries = 30): T {
  let item = pickOne(bank)
  for (let i = 0; i < tries; i++) {
    item = pickOne(bank)
    if (!recent.has(prefix + key(item))) break
  }
  recent.add(prefix + key(item))
  return item
}

