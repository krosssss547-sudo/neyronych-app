function genChain(level: Level): Core {
  const word = pickFresh(CHAIN_SHOWN, (w) => w, 'ch')
  const L = word[word.length - 1]
  const answer = pickOne((CHAIN_BY_FIRST[L] || []).filter((x) => x !== word))
  const cands = CHAIN_WORDS.filter((x) => x[0] !== L && x !== word)
  const decoys: string[] = []
  const firsts = new Set<string>()
  // На втором и третьем уровне неверные слова «похожи»: содержат нужную букву или заканчиваются ею
  const score = (x: string) => (level === 1 ? 0 : level === 2 ? (x.includes(L) ? 1 : 0) : (x.endsWith(L) ? 2 : x.includes(L) ? 1 : 0))
  const sorted = shuffle(cands).sort((a, b) => score(b) - score(a))
  for (const x of sorted) {
    if (firsts.has(x[0])) continue
    firsts.add(x[0])
    decoys.push(x)
    if (decoys.length >= 3) break
  }
  return {
    question: `Слово: ${word}\nНайди слово, которое начинается на последнюю букву`,
    correct: answer,
    options: shuffle([answer, ...decoys]),
    explanation: `Слово «${word}» заканчивается на «${L.toUpperCase()}», а «${answer}» начинается с этой буквы.`,
  }
}

function maxCount(w: string): number {
  const m: Record<string, number> = {}
  let best = 0
  for (const ch of w) { m[ch] = (m[ch] || 0) + 1; if (m[ch] > best) best = m[ch] }
  return best
}

const SUM_SOURCE: string[] = [...new Set([...ALL_KNOWN].filter((w) => /^[а-я]+$/.test(w) && w.length >= 5 && w.length <= 12))]
const SUM_POOL: Record<Level, string[]> = {
  1: SUM_SOURCE.filter((w) => w.length <= 7),
  2: SUM_SOURCE.filter((w) => w.length >= 8),
  3: SUM_SOURCE.filter((w) => w.length >= 7 && maxCount(w) >= 3 && maxCount(w) <= 4),
}

function letterCounts(w: string): Record<string, number> {
  const m: Record<string, number> = {}
  for (const ch of w) m[ch] = (m[ch] || 0) + 1
  return m
}

function genSumWords(level: Level): Core {
  const lo = level === 3 ? 3 : 1
  const hi = level === 3 ? 4 : level === 2 ? 3 : 3
  let word = ''
  let letter = ''
  let count = 0
  for (let i = 0; i < 60; i++) {
    word = pickFresh(SUM_POOL[level], (w) => w, 'sw')
    const opts = Object.entries(letterCounts(word)).filter(([, c]) => c >= lo && c <= hi)
    // на 1 уровне чаще берём повторяющиеся буквы, чтобы задача была интереснее
    const good = level === 1 ? opts.filter(([, c]) => c >= 2) : level === 2 ? opts.filter(([, c]) => c >= 2) : opts
    const use = good.length > 0 && (level !== 1 || Math.random() < 0.7) ? good : opts
    if (use.length === 0) continue
    ;[letter, count] = pickOne(use)
    break
  }
  const marked = word.split('').map((ch) => (ch === letter ? ch.toUpperCase() : ch)).join('-')
  return {
    question: `Сколько букв «${letter}» в слове «${word}»?`,
    correct: String(count),
    options: numberOptions(count, [count + 1, count - 1, count + 2, count - 2, count + 3], 3),
    explanation: `В слове «${word}» буква «${letter}» встречается ${count} ${plural(count, 'раз', 'раза', 'раз')}: ${marked}.`,
  }
}

// ───────── Выбор вида и сборка ─────────

const WEIGHTS: { kind: string; w: number }[] = [
  { kind: 'anagram', w: 20 }, { kind: 'missing', w: 18 }, { kind: 'synonym', w: 14 }, { kind: 'antonym', w: 14 },
  { kind: 'spelling', w: 14 }, { kind: 'chain', w: 12 }, { kind: 'sumwords', w: 8 },
]

let lastKind = ''

function pickKind(): string {
  const options = WEIGHTS.filter((o) => o.kind !== lastKind)
  const sum = options.reduce((a, o) => a + o.w, 0)
  let r = Math.random() * sum
  for (const o of options) {
    r -= o.w
    if (r <= 0) return o.kind
  }
  return options[0].kind
}

export function generateWords(level: Level): GameTask {
  const kind = pickKind()
  lastKind = kind
  const core =
    kind === 'anagram' ? genAnagram(level)
    : kind === 'missing' ? genMissing(level)
    : kind === 'synonym' ? genSynonym(level)
    : kind === 'antonym' ? genAntonym(level)
    : kind === 'spelling' ? genSpelling(level)
    : kind === 'chain' ? genChain(level)
    : genSumWords(level)
  const timeLimit = TIME[level]
  const task: GameTask = {
    topic: 'words',
    kind,
    kindLabel: WORDS_KINDS[kind],
    level,
    layout: 'choice',
    question: core.question,
    options: core.options,
    correct: core.correct,
    explanation: core.explanation,
    xp: XP_BY_LEVEL[level],
    fastSeconds: round1(timeLimit / 3),
    timeLimit,
  }
  if (core.intro) task.intro = core.intro
  if (core.stimulus) task.stimulus = core.stimulus
  if (core.chip) task.chip = core.chip
  return task
}