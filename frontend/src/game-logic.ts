const ALPH = 'АБВГДЕЖЗИКЛМНОПРСТУФХЦЧШЩЭЮЯ'.split('')
const LN = ALPH.length
const stepStr = (d: number) => (d >= 0 ? `+${d}` : `−${-d}`)
const places = (n: number) => `${n} ${plural(n, 'место', 'места', 'мест')}`

// Все «разумные» продолжения ряда: постоянный шаг, чередование двух шагов,
// два ряда через одну букву, растущие шаги. Верное задание допускает ровно одно продолжение.
function nextCandidates(seq: number[]): Set<number> {
  const res = new Set<number>()
  const n = seq.length
  const d = seq.slice(1).map((v, i) => v - seq[i])
  if (n >= 3 && d.every((x) => x === d[0])) res.add(seq[n - 1] + d[0])
  if (n >= 5 && d.every((x, i) => x === d[i % 2])) res.add(seq[n - 1] + d[(n - 1) % 2])
  if (n >= 6) {
    const s0 = seq.filter((_, i) => i % 2 === 0)
    const s1 = seq.filter((_, i) => i % 2 === 1)
    const ok = (s: number[]) => s.length >= 3 && s.every((v, i) => i === 0 || v - s[i - 1] === s[1] - s[0])
    if (ok(s0) && ok(s1)) res.add(seq[n - 2] + (n % 2 === 0 ? s0[1] - s0[0] : s1[1] - s1[0]))
  }
  if (n >= 5) {
    const d2 = d.slice(1).map((v, i) => v - d[i])
    if (d2.every((x) => x === d2[0])) res.add(seq[n - 1] + d[n - 2] + d2[0])
  }
  return new Set([...res].filter((v) => v >= 0 && v < LN))
}

type Built = { full: number[]; shown: number; why: string }

function buildLetters(level: Level): Built | null {
  const L = (i: number) => ALPH[i]
  if (level === 1) {
    const s = rand(2, 4)
    const start = rand(0, LN - 1 - 4 * s)
    const full = [0, 1, 2, 3, 4].map((i) => start + i * s)
    return { full, shown: 4, why: `Каждая следующая буква стоит на ${places(s)} дальше по алфавиту: ${full.map(L).join(' → ')}.` }
  }
  if (level === 2) {
    if (Math.random() < 0.55) {
      const [a, b] = pickOne([[1, 3], [2, 1], [3, 1], [2, 3], [1, 2], [3, 2], [4, 1], [1, 4], [3, -1], [4, -2], [2, -1], [5, -2]])
      const full = [0]
      for (let i = 0; i < 5; i++) full.push(full[i] + (i % 2 === 0 ? a : b))
      const lo = Math.min(...full), hi = Math.max(...full)
      if (LN - 1 - hi < -lo) return null
      const start = rand(-lo, LN - 1 - hi)
      const seq = full.map((v) => v + start)
      return { full: seq, shown: 5, why: `Шаги чередуются: ${stepStr(a)}, ${stepStr(b)}, ${stepStr(a)}, ${stepStr(b)}… Следующий шаг ${stepStr(a)}: ${seq.map(L).join(' → ')}.` }
    }
    const s = rand(2, 4)
    const shown = rand(4, 5)
    const start = rand(shown * s, LN - 1)
    const full = Array.from({ length: shown + 1 }, (_, i) => start - i * s)
    return { full, shown, why: `Каждая следующая буква стоит на ${places(s)} ближе к началу алфавита: ${full.map(L).join(' → ')}.` }
  }
  if (Math.random() < 0.55) {
    const s1 = pickOne([1, 2, 3])
    const s2 = pickOne([-3, -2, -1, 1, 2, 3].filter((x) => x !== s1))
    const a0 = rand(0, LN - 1 - 3 * s1)
    const b0 = s2 > 0 ? rand(0, LN - 1 - 3 * s2) : rand(-3 * s2, LN - 1)
    if (a0 + 3 * s1 >= LN) return null
    const full: number[] = []
    for (let i = 0; i < 4; i++) full.push(a0 + i * s1, b0 + i * s2)
    if (full.some((v) => v < 0 || v >= LN)) return null
    const shown = rand(6, 7)
    const s0 = full.filter((_, i) => i % 2 === 0), sB = full.filter((_, i) => i % 2 === 1)
    return { full, shown, why: `Ряд составлен из двух рядов, буквы которых чередуются: ${s0.map(L).join(' ')} (шаг ${stepStr(s1)}) и ${sB.map(L).join(' ')} (шаг ${stepStr(s2)}).` }
  }
  const d0 = rand(1, 2)
  const dir = Math.random() < 0.6 ? 1 : -1
  const steps = [0, 1, 2, 3, 4].map((i) => (d0 + i) * dir)
  const total = steps.reduce((a, b) => a + b, 0)
  const start = dir > 0 ? rand(0, LN - 1 - total) : rand(-total, LN - 1)
  const full = [start]
  for (const st of steps) full.push(full[full.length - 1] + st)
  if (full.some((v) => v < 0 || v >= LN)) return null
  return { full, shown: 5, why: `Шаги растут: ${steps.slice(0, 4).map(stepStr).join(', ')}, а дальше ${stepStr(steps[4])}: ${full.map(L).join(' → ')}.` }
}

function genLetters(level: Level): GameTask {
  let b: Built | null = null
  for (let g = 0; g < 200 && !b; g++) {
    const c = buildLetters(level)
    if (!c || c.full.some((v) => v < 0 || v >= LN)) continue
    const shownSeq = c.full.slice(0, c.shown)
    const cands = nextCandidates(shownSeq)
    if (cands.size === 1 && cands.has(c.full[c.shown])) b = c
  }
  if (!b) b = { full: [0, 2, 4, 6, 8], shown: 4, why: `Каждая следующая буква стоит на ${places(2)} дальше по алфавиту.` }
  const shownSeq = b.full.slice(0, b.shown)
  const ans = b.full[b.shown]
  const last = shownSeq[shownSeq.length - 1]
  const prev = shownSeq[shownSeq.length - 2]
  const pool = [ans + 1, ans - 1, ans + 2, ans - 2, ans + 3, ans - 3, last + (last - prev), prev, last]
  const wrongs = [...new Set(pool)].filter((v) => v >= 0 && v < LN && v !== ans).map((v) => ALPH[v])
  return mk(level, 'letters', {
    question: `Продолжи ряд: ${shownSeq.map((v) => ALPH[v]).join(' ')} ?`,
    options: uniqueOptions(ALPH[ans], wrongs),
    correct: ALPH[ans],
    explanation: b.why,
  })
}

// ───────── 6. Дни недели ─────────

const DAYS = ['понедельник', 'вторник', 'среда', 'четверг', 'пятница', 'суббота', 'воскресенье']
const mod7 = (n: number) => ((n % 7) + 7) % 7
const was = (d: number) => (d === 6 ? 'было' : d === 2 || d === 4 || d === 5 ? 'была' : 'был')
const dayWord = (n: number) => plural(n, 'день', 'дня', 'дней')

// Ссылка на день относительно сегодня: смещение o из −2..2
function refCore(o: number, d: number): string {
  const day = DAYS[d]
  if (o === 0) return `сегодня ${day}`
  if (o === -1) return `вчера ${was(d)} ${day}`
  if (o === -2) return `позавчера ${was(d)} ${day}`
  if (o === 1) return `завтра будет ${day}`
  return `послезавтра будет ${day}`
}
const REF_Q: Record<number, string> = {
  [-2]: 'какой день был позавчера', [-1]: 'какой день был вчера', 0: 'какой день сегодня',
  1: 'какой день будет завтра', 2: 'какой день будет послезавтра',
}
const REF_GEN: Record<number, string> = {
  [-2]: 'позавчерашнего', [-1]: 'вчерашнего', 0: 'сегодняшнего', 1: 'завтрашнего', 2: 'послезавтрашнего',
}

function genDays(level: Level): GameTask {
  const r = level === 1 && Math.random() < 0.5 ? 0 : level === 2 && Math.random() < 0.6 ? 0 : rand(-2, 2)
  const today = rand(0, 6)
  const known = mod7(today + r)
  let q: number // смещение искомого дня относительно сегодня
  let qText: string
  if (level === 1) {
    if (Math.random() < 0.5) {
      do { q = rand(-2, 2) } while (q === r)
      qText = REF_Q[q]
    } else {
      const n = rand(2, 6)
      q = Math.random() < 0.6 ? n : -n
      qText = q > 0 ? `какой день будет через ${n} ${dayWord(n)}` : `какой день был ${n} ${dayWord(n)} назад`
    }
  } else if (level === 2) {
    const n = rand(8, 30)
    q = Math.random() < 0.65 ? n : -n
    qText = q > 0 ? `какой день будет через ${n} ${dayWord(n)}` : `какой день был ${n} ${dayWord(n)} назад`
  } else if (Math.random() < 0.65) {
    const b = rand(-2, 2), n = rand(2, 20)
    if (Math.random() < 0.5) { q = b + n; qText = `какой день недели через ${n} ${dayWord(n)} после ${REF_GEN[b]} дня` }
    else { q = b - n; qText = `какой день недели за ${n} ${dayWord(n)} до ${REF_GEN[b]} дня` }
  } else {
    const n = rand(30, 100)
    q = Math.random() < 0.6 ? n : -n
    qText = q > 0 ? `какой день будет через ${n} ${dayWord(n)}` : `какой день был ${n} ${dayWord(n)} назад`
  }
  const core = refCore(r, known)
  const useIf = level === 1 && qText.startsWith('какой день') && Math.random() < 0.4
  const stimulus = useIf ? undefined : `${cap(core)}.`
  const question = useIf ? `Если ${core}, то ${qText}?` : `${cap(qText)}?`
  const ans = mod7(today + q)
  const wrongPool = [ans + 1, ans - 1, today - q, today + q + 1, today - q + 1, today - q - 1, today, known].map(mod7)
  const wrongs = [...new Set(wrongPool)].filter((v) => v !== ans)
  for (let i = 0; wrongs.length < 3; i++) if (i !== ans && !wrongs.includes(i)) wrongs.push(i)
  const abs = Math.abs(q)
  const shift = abs >= 7
    ? `Целые недели день недели не меняют, остаётся сдвиг на ${mod7(abs)} ${dayWord(mod7(abs))} ${q > 0 ? 'вперёд' : 'назад'}`
    : `Нужный день на ${abs} ${dayWord(abs)} ${q > 0 ? 'позже' : 'раньше'}, чем сегодня`
  const why = `${r === 0 ? '' : `Значит, сегодня ${DAYS[today]}. `}${abs === 0 ? 'Нужный день — сегодняшний' : abs >= 7 && abs % 7 === 0 ? `${abs} ${dayWord(abs)} — это ровно ${abs / 7} ${plural(abs / 7, 'неделя', 'недели', 'недель')}, день недели не меняется` : shift}: ${DAYS[ans]}.`
  return mk(level, 'days', {
    question,
    ...(stimulus ? { stimulus } : {}),
    options: shuffle([DAYS[ans], ...shuffle(wrongs).slice(0, 3).map((i) => DAYS[i])]),
    correct: DAYS[ans],
    explanation: why,
  })
}

// ───────── 7. Загаданное число ─────────

type Op = { o: '+' | '−' | '×' | '÷'; n: number }

function opPhrase(op: Op, first: boolean, alt: boolean): string {
  switch (op.o) {
    case '×': return first ? `умножил его на ${op.n}` : alt ? `результат умножил на ${op.n}` : `умножил на ${op.n}`
    case '÷': return first ? `разделил его на ${op.n}` : alt ? `результат разделил на ${op.n}` : `разделил на ${op.n}`
    case '+': return first ? `прибавил к нему ${op.n}` : alt ? `к результату прибавил ${op.n}` : `прибавил ${op.n}`
    default: return first ? `вычел из него ${op.n}` : alt ? `из результата вычел ${op.n}` : `вычел ${op.n}`
  }
}
const apply = (op: Op, v: number) => (op.o === '+' ? v + op.n : op.o === '−' ? v - op.n : op.o === '×' ? v * op.n : v / op.n)
const undo = (op: Op, v: number) => (op.o === '+' ? v - op.n : op.o === '−' ? v + op.n : op.o === '×' ? v / op.n : v * op.n)
const INV: Record<string, string> = { '+': '−', '−': '+', '×': '÷', '÷': '×' }

function buildUnknown(level: Level): { x: number; ops: Op[]; r: number } | null {
  const x = level === 1 ? rand(3, 25) : level === 2 ? rand(3, 60) : rand(4, 80)
  const count = level === 1 ? 2 : level === 2 ? rand(2, 3) : rand(3, 4)
  const limit = level === 1 ? 120 : 400
  let cur = x
  const ops: Op[] = []
  for (let i = 0; i < count; i++) {
    const cand: Op[] = []
    const ds = [2, 3, 4, 5, 6, 8, 9].filter((d) => cur % d === 0 && cur / d >= 2)
    if (level === 1) {
      if (i === 0) {
        cand.push({ o: '×', n: rand(2, 9) })
        if (ds.length) cand.push({ o: '÷', n: pickOne(ds) })
      } else {
        cand.push({ o: '+', n: rand(2, 20) })
        if (cur > 3) cand.push({ o: '−', n: rand(1, Math.min(20, cur - 1)) })
      }
    } else {
      cand.push({ o: '+', n: rand(2, 25) })
      if (cur > 3) cand.push({ o: '−', n: rand(2, Math.min(25, cur - 1)) })
      cand.push({ o: '×', n: rand(2, 5) })
      if (ds.length) cand.push({ o: '÷', n: pickOne(ds) })
    }
    const prev = ops.length ? ops[ops.length - 1].o : ''
    const ok = cand.filter((c) => c.o !== prev && Number.isInteger(apply(c, cur)) && apply(c, cur) >= 1 && apply(c, cur) <= limit)
    if (!ok.length) return null
    const op = pickOne(ok)
    ops.push(op)
    cur = apply(op, cur)
  }
  if (level >= 2 && !ops.some((o) => o.o === '×' || o.o === '÷')) return null
  if (level === 3 && !(ops.some((o) => o.o === '÷') && ops.some((o) => o.o === '×'))) return null
  return { x, ops, r: cur }
}

function genUnknown(level: Level): GameTask {
  let b = buildUnknown(level)
  for (let g = 0; g < 300 && !b; g++) b = buildUnknown(level)
  if (!b) b = { x: 8, ops: [{ o: '×', n: 3 }, { o: '−', n: 4 }], r: 20 }
  const { x, ops, r } = b
  const altIdx = ops.length > 1 && Math.random() < 0.6 ? rand(1, ops.length - 1) : -1
  const phrases = ops.map((op, i) => opPhrase(op, i === 0, i === altIdx))
  const joined = phrases.length === 2 ? `${phrases[0]} и ${phrases[1]}` : `${phrases.slice(0, -1).join(', ')} и ${phrases[phrases.length - 1]}`
  // типичные ошибки: обратные действия в неправильном порядке, пропущенное действие, действие без «обратного»
  const traps: number[] = []
  let c = r
  for (const op of ops) c = undo(op, c)
  traps.push(c)
  let skip = r
  const sk = rand(0, ops.length - 1)
  for (let i = ops.length - 1; i >= 0; i--) if (i !== sk) skip = undo(ops[i], skip)
  traps.push(skip)
  let same = r
  const sm = rand(0, ops.length - 1)
  for (let i = ops.length - 1; i >= 0; i--) same = i === sm ? apply(ops[i], same) : undo(ops[i], same)
  traps.push(same)
  const good = traps.filter((t) => Number.isInteger(t) && t >= 1 && t <= 200 && t !== x)
  const steps: string[] = []
  let cur = r
  for (let i = ops.length - 1; i >= 0; i--) {
    const nx = undo(ops[i], cur)
    steps.push(`${cur} ${INV[ops[i].o]} ${ops[i].n} = ${nx}`)
    cur = nx
  }
  return mk(level, 'unknown', {
    question: `Я задумал число, ${joined} — получилось ${r}. Какое число я задумал?`,
    options: numberOptions(x, good, level === 1 ? 8 : 12),
    correct: String(x),
    explanation: `Идём с конца обратными действиями: ${steps.join(', ')}. Задумано число ${x}.`,
  })
}

// ───────── Выбор вида ─────────

const WEIGHTS: { kind: string; w: number }[] = [
  { kind: 'order', w: 16 }, { kind: 'syllogism', w: 16 }, { kind: 'analogy', w: 16 }, { kind: 'oddword', w: 14 },
  { kind: 'letters', w: 14 }, { kind: 'days', w: 10 }, { kind: 'unknown', w: 14 },
]

let lastKind = ''

function pickKind(): string {
  const opts = WEIGHTS.filter((o) => o.kind !== lastKind)
  let r = Math.random() * opts.reduce((a, o) => a + o.w, 0)
  for (const o of opts) {
    r -= o.w
    if (r <= 0) return o.kind
  }
  return opts[0].kind
}

export function generateLogic(level: Level): GameTask {
  const kind = pickKind()
  lastKind = kind
  switch (kind) {
    case 'order': return genOrder(level)
    case 'syllogism': return genSyllogism(level)
    case 'analogy': return genAnalogy(level)
    case 'oddword': return genOddword(level)
    case 'letters': return genLetters(level)
    case 'days': return genDays(level)
    default: return genUnknown(level)
  }
}

