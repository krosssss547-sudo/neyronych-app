type Body = {
  question: string
  stimulus?: string
  size?: 'md' | 'lg' | 'xl'
  options: string[]
  correct: string
  explanation: string
}

function mk(level: Level, kind: string, b: Body): GameTask {
  return {
    topic: 'logic',
    kind,
    kindLabel: LOGIC_KINDS[kind],
    level,
    layout: 'choice',
    question: b.question,
    ...(b.stimulus !== undefined ? { stimulus: { type: 'text' as const, text: b.stimulus, size: b.size ?? 'lg' } } : {}),
    options: b.options,
    correct: b.correct,
    explanation: b.explanation,
    xp: XP_BY_LEVEL[level],
    fastSeconds: FAST[kind][level - 1],
  }
}

// Согласование числительного с существительным: 1 день, 2 дня, 5 дней, 21 день
function plural(n: number, one: string, few: string, many: string): string {
  const a = Math.abs(n) % 100
  const b = a % 10
  if (a > 10 && a < 20) return many
  if (b === 1) return one
  if (b >= 2 && b <= 4) return few
  return many
}
