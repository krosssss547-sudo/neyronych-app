const FICT = ['зурб', 'нарф', 'дарб', 'мулт', 'вокс', 'тарк', 'ломп', 'бекс', 'рыск', 'флиц', 'кульп', 'трыж']
function fictNoun(sg: string): Noun {
  const last = sg[sg.length - 1]
  const pl = sg + ('кгхжчшщ'.includes(last) ? 'и' : 'ы')
  const ins = sg + ('жчшщц'.includes(last) ? 'ем' : 'ом')
  return { sg, pl, ins, g: 'm' }
}

const recentChain = makeRecent(10)
function pickChain(): [string, string, Who] {
  for (let g = 0; g < 30; g++) {
    const c = pickOne(CHAINS)
    const id = c[0] + '>' + c[1]
    if (!recentChain.has(id)) { recentChain.add(id); return c }
  }
  return pickOne(CHAINS)
}

const ni = (n: Noun) => `Ни ${n.g === 'm' ? 'один' : n.g === 'f' ? 'одна' : 'одно'} ${n.sg} не является ${'#'}`
const allS = (a: Noun, b: Noun) => `Все ${a.pl} — ${b.pl}.`
const noneS = (a: Noun, c: Noun) => ni(a).replace('#', c.ins) + '.'

type Form = 'a' | 'b' | 'c' | 'd' | 'e' | 'f' | 'g'

function genSyllogism(level: Level): GameTask {
  const fict = level === 1 ? false : level === 2 ? Math.random() < 0.25 : Math.random() < 0.65
  const forms: Form[] = level === 3
    ? ['a', 'a', 'b', 'b', 'c', 'd', 'd', 'e', 'e', 'f', 'f', 'g', 'g']
    : level === 2 ? ['a', 'a', 'a', 'b', 'b', 'b', 'c', 'c', 'd', 'd'] : ['a', 'a', 'a', 'a', 'b', 'b', 'b', 'c', 'c', 'd', 'd']
  const form = pickOne(forms)
  const f3 = shuffle(FICT).slice(0, 3).map(fictNoun)

  let A: Noun, B: Noun, C: Noun = f3[2]
  let who: Who | 'object' = 'object'
  const realChain = () => { const c = pickChain(); A = NOUNS[c[0]]; B = NOUNS[c[1]]; who = c[2] }
  const prem: string[] = []
  let q = '', answer = '', why = ''
  A = f3[0]; B = f3[1]

  if (form === 'a' || form === 'b') {
    if (!fict) realChain()
    const [S, s] = subject(who)
    if (form === 'a') {
      prem.push(allS(A, B), `${S} — ${A.sg}.`)
      q = `Верно ли, что ${s} — ${B.sg}?`
      answer = 'Да'
      why = `Все ${A.pl} — ${B.pl}, а ${s} — ${A.sg}. Значит, ${s} — ${B.sg}.`
    } else {
      prem.push(allS(A, B), `${S} — ${B.sg}.`)
      q = `Верно ли, что ${s} — ${A.sg}?`
      answer = 'Нельзя определить'
      why = `Не все ${B.pl} — ${A.pl}, поэтому из того, что ${s} — ${B.sg}, вывод сделать нельзя.`
    }
  } else if (form === 'c') {
    if (!fict) {
      const d = pickOne(DISJOINT)
      A = NOUNS[d[0]]; C = NOUNS[d[1]]; who = d[2]
    } else { A = f3[0]; C = f3[1] }
    const [S, s] = subject(who)
    prem.push(noneS(A, C), `${S} — ${A.sg}.`)
    q = `Верно ли, что ${s} — ${C.sg}?`
    answer = 'Нет'
    why = `${cap(s)} — ${A.sg}, а ${A.sg} не бывает ${C.ins}. Значит, ${s} — не ${C.sg}.`
  } else if (form === 'd') {
    if (!fict) realChain()
    const [S, s] = subject('object')
    prem.push(allS(A, B), `${S} — не ${B.sg}.`)
    q = `Верно ли, что ${s} — ${A.sg}?`
    answer = 'Нет'
    why = `Все ${A.pl} — ${B.pl}, а ${s} — не ${B.sg}. Значит, ${s} не может быть ${A.ins}.`
  } else {
    // Три группы: e, f — цепочка A ⊂ B ⊂ C; g — A ⊂ B, а B и C не пересекаются
    let found = false
    if (!fict) {
      const links = form === 'g' ? DISJOINT : CHAINS
      for (let t = 0; t < 40 && !found; t++) {
        const c1 = pickOne(CHAINS)
        const nexts = links.filter((l) => l[0] === c1[1])
        if (nexts.length) {
          const l2 = pickOne(nexts)
          A = NOUNS[c1[0]]; B = NOUNS[c1[1]]; C = NOUNS[l2[1]]; who = c1[2]; found = true
        }
      }
    }
    if (!found) { A = f3[0]; B = f3[1]; C = f3[2]; who = 'object' }
    const [S, s] = subject(who)
    if (form === 'e') {
      prem.push(allS(A, B), allS(B, C), `${S} — ${A.sg}.`)
      q = `Верно ли, что ${s} — ${C.sg}?`
      answer = 'Да'
      why = `${cap(s)} — ${A.sg}, значит и ${B.sg}, а раз все ${B.pl} — ${C.pl}, то ${s} — ${C.sg}.`
    } else if (form === 'f') {
      prem.push(allS(A, B), allS(B, C), `${S} — ${C.sg}.`)
      q = `Верно ли, что ${s} — ${A.sg}?`
      answer = 'Нельзя определить'
      why = `Не все ${C.pl} — ${A.pl}, поэтому из того, что ${s} — ${C.sg}, вывод сделать нельзя.`
    } else {
      prem.push(allS(A, B), noneS(B, C), `${S} — ${A.sg}.`)
      q = `Верно ли, что ${s} — ${C.sg}?`
      answer = 'Нет'
      why = `${cap(s)} — ${A.sg}, значит и ${B.sg}, а ${B.sg} не бывает ${C.ins}. Значит, ${s} — не ${C.sg}.`
    }
  }
  return mk(level, 'syllogism', {
    question: q,
    stimulus: (level === 3 ? shuffle(prem) : prem).join('\n'),
    options: ['Да', 'Нет', 'Нельзя определить'],
    correct: answer,
    explanation: why,
  })
}

