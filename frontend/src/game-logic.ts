const ORD = ['первый', 'второй', 'третий', 'четвёртый', 'пятый']

function pickPeople(n: number): [string, string][] {
  for (let g = 0; g < 50; g++) {
    const ps = shuffle(PEOPLE).slice(0, n)
    if (new Set(ps.map((p) => p[0][0])).size === n) return ps
  }
  return shuffle(PEOPLE).slice(0, n)
}

function genOrder(level: Level): GameTask {
  const n = level + 2
  const dom = pickOne(DOMAINS)
  const ps = pickPeople(n) // ps[0] — «самый-самый» сверху, ps[n-1] — снизу
  const lines: string[] = []
  for (let i = 0; i < n - 1; i++) {
    lines.push(Math.random() < 0.5 ? `${ps[i][0]} ${dom.up} ${ps[i + 1][1]}` : `${ps[i + 1][0]} ${dom.down} ${ps[i][1]}`)
  }
  let r: number // индекс в ряду сверху вниз
  let question: string
  if (level === 1 || Math.random() < 0.4) {
    if (Math.random() < 0.5) { r = 0; question = `Кто ${dom.top}?` } else { r = n - 1; question = `Кто ${dom.bottom}?` }
  } else {
    const k = rand(2, n - 1)
    if (Math.random() < 0.5) { r = k - 1; question = `Кто ${ORD[k - 1]} ${dom.by}, если считать от самого ${dom.topG}?` }
    else { r = n - k; question = `Кто ${ORD[k - 1]} ${dom.by}, если считать от самого ${dom.botG}?` }
  }
  const correct = ps[r][0]
  const others = ps.filter((_, i) => i !== r).map((p) => p[0])
  const options = level === 3 ? shuffle([correct, ...shuffle(others).slice(0, 3)]) : shuffle([correct, ...others])
  return mk(level, 'order', {
    question,
    stimulus: shuffle(lines).join('\n'),
    options,
    correct,
    explanation: `Выстроим цепочку (${dom.top} → ${dom.bottom}): ${ps.map((p) => p[0]).join(', ')}. Ответ: ${correct}.`,
  })
}

