// Подлежащее: [в начале предложения, в середине предложения]
function subject(who: Who | 'object'): [string, string] {
  if (who === 'animal') { const n = pickOne(ANIMAL_NAMES); return [n, n] }
  if (who === 'person') { const n = pickOne(PERSON_NAMES); return [n, n] }
  const label = who === 'plant' ? 'растение' : who === 'shape' ? 'фигура' : who === 'thing' ? 'предмет' : 'объект'
  const tag = pickOne(LETTER_TAGS)
  return [`${cap(label)} ${tag}`, `${label} ${tag}`]
}

