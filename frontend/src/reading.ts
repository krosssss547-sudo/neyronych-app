function genFlashWords(level: Level): ReadingTask {
  const k = level === 1 ? 3 : level === 2 ? 4 : 5
  const showMs = level === 1 ? 1600 : level === 2 ? 1400 : 1200
  const target = pickN(WORDS, k)
  const correct = target.join(' · ')
  const options = new Set<string>([correct])
  const positions = shuffle(Array.from({ length: k }, (_, i) => i))
  let guard = 0
  while (options.size < 4 && guard++ < 100) {
    const pos = positions[(options.size - 1) % k]
    const replacement = pickOne(WORDS.filter((w) => !target.includes(w)))
    const variant = target.map((w, i) => (i === pos ? replacement : w)).join(' · ')
    options.add(variant)
  }
  return {
    ...base(level, 'flash', 'flash'),
    intro: `Сейчас на ${(showMs / 1000).toFixed(1).replace('.', ',')} с появятся ${k} слов${k === 5 ? '' : 'а'}. Запомни их точно.`,
    passage: correct, showMs,
    question: 'Какие слова ты видел(а)?', options: shuffle([...options]), correct,
    explanation: `Были слова: ${correct}`,
  }
}

function groupDigits(s: string): string {
  return s.replace(/\B(?=(\d{3})+(?!\d))/g, ' ')
}

function genDigits(level: Level): ReadingTask {
  const len = level === 1 ? 5 : level === 2 ? 7 : 9
  const showMs = level === 1 ? 1500 : level === 2 ? 1600 : 1800
  const digits = Array.from({ length: len }, (_, i) => (i === 0 ? rand(1, 9) : rand(0, 9)))
  const str = digits.join('')
  const variants = new Set<string>()
  let guard = 0
  while (variants.size < 3 && guard++ < 200) {
    const d = [...digits]
    const mode = rand(0, 2)
    if (mode === 0) {
      const i = rand(0, len - 2)
      ;[d[i], d[i + 1]] = [d[i + 1], d[i]]
    } else if (mode === 1) {
      const i = rand(0, len - 1)
      d[i] = (d[i] + rand(1, 9)) % 10
    } else {
      d[len - 1] = (d[len - 1] + rand(1, 9)) % 10
    }
    if (d[0] === 0) continue
    const v = d.join('')
    if (v !== str) variants.add(v)
  }
  const options = shuffle([str, ...variants].map(groupDigits))
  return {
    ...base(level, 'digits', 'flash'),
    intro: `Сейчас на ${(showMs / 1000).toFixed(1).replace('.', ',')} с появится ${len}-значное число. Запомни его.`,
    passage: groupDigits(str), showMs,
    question: 'Какое число ты видел(а)?', options, correct: groupDigits(str),
    explanation: `Было число ${groupDigits(str)}`,
  }
}

