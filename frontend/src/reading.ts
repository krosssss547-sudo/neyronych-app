export type ReadingProfile = {
  solved: number
  total: number
  peakWpm: number                                  // лучшая средняя скорость (по последним верным чтениям)
  recent: number[]                                 // скорость последних верных чтений (до 10)
  kinds: Record<string, { t: number; c: number }>
}

const PROFILE_KEY = 'neyronych_reading_profile_v1'
export const BONUS_XP = 5

export function loadReadingProfile(): ReadingProfile {
  try {
    const raw = localStorage.getItem(PROFILE_KEY)
    if (raw) {
      const p = JSON.parse(raw)
      return {
        solved: Number(p.solved) || 0,
        total: Number(p.total) || 0,
        peakWpm: Number(p.peakWpm) || 0,
        recent: Array.isArray(p.recent) ? p.recent.map(Number).filter((x: number) => x > 0).slice(-10) : [],
        kinds: p.kinds && typeof p.kinds === 'object' ? p.kinds : {},
      }
    }
  } catch { /* localStorage может быть недоступен */ }
  return { solved: 0, total: 0, peakWpm: 0, recent: [], kinds: {} }
}

export function saveReadingProfile(p: ReadingProfile): void {
  try { localStorage.setItem(PROFILE_KEY, JSON.stringify(p)) } catch { /* ignore */ }
}

export function averageWpm(p: ReadingProfile): number {
  if (p.recent.length < 3) return 0
  return Math.round(p.recent.reduce((a, b) => a + b, 0) / p.recent.length)
}

// wpm учитывается только для верного ответа на текст
export function recordReadingResult(p: ReadingProfile, kind: string, ok: boolean, wpm: number | null): ReadingProfile {
  const prev = p.kinds[kind] || { t: 0, c: 0 }
  const recent = ok && wpm !== null ? [...p.recent, wpm].slice(-10) : p.recent
  const next: ReadingProfile = {
    solved: p.solved + (ok ? 1 : 0),
    total: p.total + 1,
    peakWpm: p.peakWpm,
    recent,
    kinds: { ...p.kinds, [kind]: { t: prev.t + 1, c: prev.c + (ok ? 1 : 0) } },
  }
  if (recent.length >= 5) next.peakWpm = Math.max(p.peakWpm, averageWpm(next))
  return next
}

export type SpeedTier = { min: number; name: string; emoji: string }

export const SPEED_TIERS: SpeedTier[] = [
  { min: 0, name: 'Разгон', emoji: '🐢' },
  { min: 150, name: 'Читатель', emoji: '📖' },
  { min: 250, name: 'Быстрый взгляд', emoji: '👁' },
  { min: 350, name: 'Скоростной', emoji: '🚀' },
  { min: 500, name: 'Реактивный', emoji: '⚡' },
]

export function getSpeedTier(wpm: number): { tier: SpeedTier; next: SpeedTier | null; progressPct: number; toNext: number } {
  let i = 0
  for (let k = 0; k < SPEED_TIERS.length; k++) if (wpm >= SPEED_TIERS[k].min) i = k
  const tier = SPEED_TIERS[i]
  const next = SPEED_TIERS[i + 1] || null
  if (!next) return { tier, next: null, progressPct: 100, toNext: 0 }
  return { tier, next, progressPct: Math.round(((wpm - tier.min) / (next.min - tier.min)) * 100), toNext: next.min - wpm }
}

export function readingKindLabel(kind: string): string {
  return LABELS[kind as ReadKindId] || kind
}

export function analyzeReading(p: ReadingProfile): { best: { label: string; pct: number } | null; worst: { label: string; pct: number } | null } {
  const rows = Object.entries(p.kinds)
    .filter(([, v]) => v.t >= 3)
    .map(([k, v]) => ({ label: readingKindLabel(k), pct: Math.round((v.c / v.t) * 100), t: v.t }))
  if (rows.length === 0) return { best: null, worst: null }
  const sorted = [...rows].sort((a, b) => b.pct - a.pct || b.t - a.t)
  const best = sorted[0]
  const worst = sorted[sorted.length - 1]
  return {
    best: { label: best.label, pct: best.pct },
    worst: worst.label !== best.label && worst.pct < 80 ? { label: worst.label, pct: worst.pct } : null,
  }
}