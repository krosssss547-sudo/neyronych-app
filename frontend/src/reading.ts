function genScan(level: Level): ReadingTask {
  const total = level === 1 ? 12 : level === 2 ? 16 : 20
  const cols = level === 1 ? 3 : 4
  const timeLimit = level === 1 ? 14 : 12
  let words: string[]
  let dup: string
  let partner: string | null = null
  if (level === 3) {
    const pairs = pickN(LOOKALIKES, 4)
    const pairWords = pairs.flat()
    const others = pickN(WORDS, total - pairWords.length - 1)
    const pool = [...pairWords, ...others]
    dup = pickOne(pool)
    const pair = pairs.find((p) => p.includes(dup))
    partner = pair ? pair.find((w) => w !== dup) ?? null : null
    words = shuffle([...pool, dup])
  } else {
    const pool = pickN(WORDS, total - 1)
    dup = pickOne(pool)
    words = shuffle([...pool, dup])
  }
  const distinct = [...new Set(words)]
  const wrongPool = shuffle(distinct.filter((w) => w !== dup && w !== partner))
  const wrong = [...(partner ? [partner] : []), ...wrongPool].slice(0, 3)
  return {
    ...base(level, 'scan', 'scan'),
    intro: 'Среди слов есть одно, которое повторяется. Найди его до конца времени.',
    words, cols, timeLimit,
    question: 'Какое слово повторяется?', options: shuffle([dup, ...wrong]), correct: dup,
    explanation: `Слово «${dup}» встречается дважды`,
  }
}

// ───────── Выбор упражнения ─────────

type Weighted = { kind: ReadKindId; w: number }

const WEIGHTS: Record<Level, Weighted[]> = {
  1: [{ kind: 'read', w: 35 }, { kind: 'detail', w: 20 }, { kind: 'flash', w: 15 }, { kind: 'digits', w: 15 }, { kind: 'scan', w: 15 }],
  2: [{ kind: 'read', w: 30 }, { kind: 'detail', w: 20 }, { kind: 'flash', w: 15 }, { kind: 'digits', w: 15 }, { kind: 'scan', w: 20 }],
  3: [{ kind: 'read', w: 30 }, { kind: 'detail', w: 20 }, { kind: 'flash', w: 15 }, { kind: 'digits', w: 15 }, { kind: 'scan', w: 20 }],
}

let lastKind: ReadKindId | '' = ''
let sinceText = 0 // сколько упражнений подряд было без текста — скорость чтения меряется только по текстам

function pickKind(level: Level): ReadKindId {
  let options = WEIGHTS[level].filter((o) => o.kind !== lastKind)
  if (sinceText >= 3) options = options.filter((o) => o.kind === 'read' || o.kind === 'detail')
  const sum = options.reduce((a, o) => a + o.w, 0)
  let r = Math.random() * sum
  for (const o of options) {
    r -= o.w
    if (r <= 0) return o.kind
  }
  return options[0].kind
}

export function generateReading(level: Level): ReadingTask {
  const kind = pickKind(level)
  lastKind = kind
  sinceText = kind === 'read' || kind === 'detail' ? 0 : sinceText + 1
  if (kind === 'read') return genRead(level)
  if (kind === 'detail') return genDetail(level)
  if (kind === 'flash') return genFlashWords(level)
  if (kind === 'digits') return genDigits(level)
  return genScan(level)
}

