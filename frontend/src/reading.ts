// Чтобы тексты не повторялись, пока не пройдены все
const used: Record<Level, Set<string>> = { 1: new Set(), 2: new Set(), 3: new Set() }

function nextPassage(level: Level): Passage {
  const pool = PASSAGES[level]
  let free = pool.filter((p) => !used[level].has(p.id))
  if (free.length === 0) { used[level].clear(); free = pool }
  const p = pickOne(free)
  used[level].add(p.id)
  return p
}

function base(level: Level, kind: ReadKindId, mode: ReadMode): Pick<ReadingTask, 'mode' | 'kind' | 'kindLabel' | 'level' | 'xp' | 'fastSeconds'> {
  return { mode, kind, kindLabel: LABELS[kind], level, xp: XP[level], fastSeconds: FAST_SECONDS }
}

function readTiming(text: string, level: Level) {
  const wordCount = countWords(text)
  const targetWpm = TARGET_WPM[level]
  const readSeconds = Math.ceil((wordCount / targetWpm) * 60) + 2
  return { wordCount, targetWpm, readSeconds }
}

function genRead(level: Level): ReadingTask {
  const p = nextPassage(level)
  const qa = pickOne(p.qa)
  const timing = readTiming(p.text, level)
  return {
    ...base(level, 'read', 'read'), ...timing,
    intro: 'Читай в своём темпе. Текст исчезнет сам, а если дочитал раньше — жми «Прочитал».',
    passage: p.text,
    question: qa.q, options: shuffle([...qa.a]), correct: qa.a[0], explanation: qa.e,
  }
}

