function numberOptions(correct: number, traps: number[], spread: number): string[] {
  const set = new Set<number>([correct])
  for (const t of traps) if (t > 0) set.add(t)
  let guard = 0
  while (set.size < 4 && guard++ < 200) {
    const v = correct + rand(-spread, spread)
    if (v > 0) set.add(v)
  }
  const rest = [...set].filter((v) => v !== correct).slice(0, 3)
  return shuffle([correct, ...rest].map(String))
}

